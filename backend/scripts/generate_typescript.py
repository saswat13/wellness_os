"""Generate frontend types from the executed OpenAPI registry; no network or SDK clients."""

import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def ts(schema):
    if "$ref" in schema:
        return "Schemas[" + json.dumps(schema["$ref"].rsplit("/", 1)[1]) + "]"
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(v) for v in schema["enum"])
    for key, separator in [("anyOf", " | "), ("oneOf", " | "), ("allOf", " & ")]:
        if key in schema:
            return "(" + separator.join(ts(v) for v in schema[key]) + ")"
    kind = schema.get("type")
    if isinstance(kind, list):
        return " | ".join(ts({**schema, "type": k}) for k in kind)
    if kind == "array":
        return "Array<" + ts(schema.get("items", {})) + ">"
    if kind == "object" or "properties" in schema:
        required = schema.get("required", [])
        fields = [
            json.dumps(k) + (":" if k in required else "?:") + ts(v)
            for k, v in schema.get("properties", {}).items()
        ]
        extra = schema.get("additionalProperties")
        if isinstance(extra, dict):
            fields.append("[key: string]:" + ts(extra))
        return "{" + ";".join(fields) + "}" if fields else "Record<string, never>"
    return {
        "string": "string",
        "number": "number",
        "integer": "number",
        "boolean": "boolean",
        "null": "null",
    }.get(kind, "unknown")


def main():
    spec = json.loads((ROOT / "backend/contracts/openapi-v1.json").read_text())
    lines = [
        "// Generated by backend/scripts/generate_typescript.py. Do not edit.",
        "export type Schemas = {",
    ]
    lines += [json.dumps(k) + ":" + ts(v) + ";" for k, v in spec["components"]["schemas"].items()]
    lines += ["};", "export type Operations = {"]
    for path, methods in spec["paths"].items():
        for method, op in methods.items():
            body = (
                op.get("requestBody", {})
                .get("content", {})
                .get("application/json", {})
                .get("schema")
            )
            response = next(v for k, v in op["responses"].items() if k.startswith("2"))
            schema = response.get("content", {}).get("application/json", {}).get("schema")
            lines.append(
                json.dumps(method.upper() + " " + path)
                + ": {body:"
                + (ts(body) if body else "never")
                + ";response:"
                + (ts(schema) if schema else "null")
                + "};"
            )
    lines += ["};", ""]
    output = subprocess.run(
        [str(ROOT / "node_modules/.bin/prettier"), "--parser", "typescript"],
        input="\n".join(lines),
        capture_output=True,
        text=True,
        check=True,
    ).stdout
    path = ROOT / "lib/api-v1.generated.ts"
    if "--check" in sys.argv:
        if path.read_text() != output:
            raise SystemExit(
                "Generated API types are stale; regenerate the executed contract/types"
            )
        print("OpenAPI TypeScript types match the committed contract")
    else:
        path.write_text(output)


if __name__ == "__main__":
    main()
