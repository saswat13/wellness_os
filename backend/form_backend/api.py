@dataclass(frozen=True)
class Route:
    method: str
    path: str
    request: type[Model] | None
    read: type[Model]
    operation: str
    status: int = 200

    def match(self, path):
        return re.fullmatch(re.sub(r"\{(\w+)\}", r"(?P<\1>[^/]+)", self.path), path)


