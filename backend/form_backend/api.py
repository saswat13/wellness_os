@dataclass(frozen=True)
class Response:
    status: int
    body: dict | None
    headers: dict

    def to_json(self):
        return json_text(self.body) if self.body is not None else ""


class API:
    def __init__(self, service, cursor_key=None):
        self.service = service
        self.cursor_key = cursor_key or secrets.token_bytes(32)

    def _page(self, records, p, path, query, request_id, model):
        limit = int(query.get("limit", "25"))
        if not 1 <= limit <= 100:
            raise Problem(422, "INVALID_LIMIT")
        items = sorted((r.dto() for r in records), key=lambda r: r["id"])
        # Preserve date order for performance/session pages, bind mutation revision digest.
        if path.endswith(("/history", "/sessions", "/active")):
            items.sort(key=lambda r: (r["startedAt"], r["id"]), reverse=True)
        fingerprint = digest([(r["id"], r["revision"], r.get("completedVersion")) for r in items])
        route_hash = digest(
            {"path": path, "query": {k: v for k, v in query.items() if k != "cursor"}}
        )
        offset = 0
        if query.get("cursor"):
            try:
                if len(query["cursor"]) > 4096:
                    raise ValueError()
                token, mac = query["cursor"].split(".")
                wanted = hmac.new(self.cursor_key, token.encode(), hashlib.sha256).hexdigest()
                if not hmac.compare_digest(mac, wanted):
                    raise ValueError()
                cursor = load_json(base64.urlsafe_b64decode(token + "=" * (-len(token) % 4)))
                if (
                    cursor["sub"] != p.subject
                    or cursor["route"] != route_hash
                    or cursor["exp"] <= self.service.uow.clock().timestamp()
                ):
                    raise ValueError()
                if cursor["snapshot"] != fingerprint:
                    raise Problem(409, "COLLECTION_CHANGED")
                offset = cursor["offset"]
                if type(offset) is not int or offset < 0:
                    raise ValueError()
            except (ValueError, KeyError, TypeError):
                raise Problem(400, "INVALID_CURSOR") from None
        selected = items[offset : offset + limit]
        next_cursor = None
        if offset + limit < len(items):
            data = {
                "sub": p.subject,
                "route": route_hash,
                "snapshot": fingerprint,
                "offset": offset + limit,
                "exp": int(self.service.uow.clock().timestamp()) + 900,
            }
            token = base64.urlsafe_b64encode(json_text(data).encode()).decode().rstrip("=")
            next_cursor = (
                token + "." + hmac.new(self.cursor_key, token.encode(), hashlib.sha256).hexdigest()
            )
        return Page[model](  # type: ignore[valid-type]  # Runtime generated response schema.
            items=tuple(model.model_validate(v) for v in selected),
            next_cursor=next_cursor,
            meta=Meta(request_id=request_id),
        ).model_dump(by_alias=True)

    def page_result(self, route, params, principal, query, request_id, path):
        result = self.execute(route, params, principal, None, 0, query)
        return result, self._page(result.data, principal, path, query, request_id, route.read)

    def handle(self, method, path, *, principal=None, body="{}", headers=None, query=None):
        request_id = str(uuid4())
        safe_headers = {
            "Cache-Control": "no-store",
            "Content-Type": "application/json",
            "X-Request-Id": request_id,
        }
        try:
            if not isinstance(principal, Principal):
                raise Problem(401, "AUTHENTICATION_REQUIRED")
            principal.require("form/read" if method == "GET" else "form/write")
            self.service.uow.subject(principal)
            route = next((r for r in ROUTES if r.method == method and r.match(path)), None)
            if not route:
                raise Problem(404, "NOT_FOUND")
            params = route.match(path).groupdict()
            query = query or {}
            allowed: set[str] = set()
            if route.operation.endswith((":list", ":history", ":active")):
                allowed.update(("limit", "cursor"))
            if route.operation == "session:list":
                allowed.update(("from", "to"))
            if route.operation in ("diary:day", "goals:get"):
                allowed.add("date")
            if any(k not in allowed for k in query):
                raise Problem(400, "UNKNOWN_QUERY_FIELD")
            headers = {k.lower(): v for k, v in (headers or {}).items()}
            if len(body.encode() if isinstance(body, str) else body) > 256 * 1024:
                raise Problem(413, "PAYLOAD_TOO_LARGE")
            try:
                raw = load_json(body)
            except (ValueError, TypeError):
                raise Problem(400, "MALFORMED_JSON") from None
            expected = 0
            if method != "GET" and route.operation.split(":")[1] != "create":
                match = re.fullmatch(r'"(0|[1-9]\d*)"', headers.get("if-match", ""))
                if not match:
                    raise Problem(428, "PRECONDITION_REQUIRED")
                expected = int(match.group(1))
            req = (
                route.request.model_validate(raw, by_alias=True, by_name=False)
                if route.request
                else None
            )
            if route.operation.endswith(":create") and hasattr(req, "id"):
                try:
                    UUID(getattr(req, "id"))
                except ValueError:
                    raise Problem(422, "UUID_REQUIRED") from None
            if method == "GET":
                if route.operation.endswith((":list", ":history", ":active")):
                    result, data = self.page_result(
                        route, params, principal, query, request_id, path
                    )
                else:
                    result = self.execute(route, params, principal, req, expected, query)
                    data = EntityResponse[route.read](  # type: ignore[name-defined]  # Runtime Pydantic resource class.
                        data=route.read.model_validate(result.data),
                        meta=Meta(request_id=request_id, revision=result.revision),
                    ).model_dump(by_alias=True)
            else:
                try:
                    UUID(headers.get("idempotency-key", ""))
                except ValueError:
                    raise Problem(400, "IDEMPOTENCY_KEY_REQUIRED") from None
                domain = "accounts" if path == "/v1/me" else path.split("/")[2]

                def action():
                    value = self.execute(route, params, principal, req, expected, query)
                    if value.status != 204:
                        route.read.model_validate(value.data)
                    return value

                result = self.service.uow.mutate(
                    principal,
                    domain,
                    method,
                    path,
                    headers.get("idempotency-key"),
                    raw,
                    expected,
                    action,
                )
                data = (
                    None
                    if result.status == 204
                    else EntityResponse[route.read](  # type: ignore[name-defined]  # Runtime Pydantic resource class.
                        data=route.read.model_validate(result.data),
                        meta=Meta(request_id=request_id, revision=result.revision),
                    ).model_dump(by_alias=True)
                )
            if result.revision is not None:
                safe_headers["ETag"] = f'"{result.revision}"'
            if result.replayed:
                safe_headers["Idempotency-Replayed"] = "true"
            if result.status == 201:
                safe_headers["Location"] = (
                    path if path == "/v1/me" else path + "/" + result.data["id"]
                )
            return Response(result.status, data, safe_headers)
        except ValidationError:
            err = Problem(422, "VALIDATION_FAILED")
        except Problem as problem:
            err = problem
        except (ValueError, TypeError, OverflowError):
            err = Problem(422, "VALIDATION_FAILED")
        except Exception:
            err = Problem(500, "INTERNAL_ERROR")
        error = ErrorResponse(
            error=ErrorDetail(code=err.code, message=err.message, request_id=request_id)
        )
        return Response(err.status, error.model_dump(by_alias=True), safe_headers)

    def execute(self, route, params, p, req, expected, query):
        s = self.service
        kind, op = route.operation.split(":")
        id = params.get("id", "profile" if kind == "profile" else "current")
        repo = (
            s.training
            if kind in ("exercise", "template", "session")
            else s.accounts
            if kind == "profile"
            else s.nutrition
        )
        if op not in ("create", "get", "list", "history", "active", "day", "version"):
            try:
                current = (
                    s.definition(p, kind, id)
                    if kind in ("exercise", "food")
                    else repo.get(p, kind, id)
                )
            except Problem as err:
                if kind != "goals" or expected != 0 or err.code != "NOT_FOUND":
                    raise
            else:
                if current.revision != expected:
                    raise Problem(412, "REVISION_CONFLICT")
        if op == "active":
            return Result(200, s.training.active_workouts(p))
        if op == "list":
            if kind == "session":
                end = (
                    timestamp(query["to"])
                    if "to" in query
                    else s.uow.clock() + timedelta(milliseconds=1)
                )
                start = timestamp(query["from"]) if "from" in query else end - timedelta(days=90)
                if start >= end or end - start > timedelta(days=366):
                    raise Problem(422, "INVALID_DATE_RANGE")
                records = s.training.workouts_between(p, start, end)
            else:
                records = repo.list(p, kind)
                if kind in ("exercise", "food"):
                    records += s.catalog.list(kind)
            return Result(200, records)
        if op == "history":
            s.definition(p, "exercise", id)
            # Page every matching performance; never silently cap lifetime history.
            return Result(200, s.training.performances(p, id, None))
        if op == "day":
            day = calendar_date(query["date"]) if "date" in query else s.today(p)
            return Result(200, s.diary(p, day))
        if kind == "goals" and op == "get":
            day = calendar_date(query["date"]) if "date" in query else s.today(p)
            record = s.goals_on(p, day)
            if not record:
                raise Problem(404, "NOT_FOUND")
            return Result(200, record.dto(), record.revision)
        if op == "get":
            record = (
                s.definition(p, kind, id) if kind in ("exercise", "food") else repo.get(p, kind, id)
            )
            return Result(200, record.dto(), record.revision)
        if op == "version":
            version = int(params["version"])
            if version < 1:
                raise Problem(404, "NOT_FOUND")
            key = "workoutVersion" if kind == "session" else "recipeVersion"
            record = repo.get(p, key, f"{id}:{version}")
            return Result(200, record.dto(), record.revision)
        if op in ("archive", "restore"):
            return s.archive(p, repo, kind, id, expected, op == "archive")
        if kind == "session":
            if op == "create":
                return s.create_session(p, req)
            if op == "draft":
                return s.write_draft(p, id, req, expected)
            if op == "update":
                return s.patch_session(p, id, req, expected)
            if op == "sets":
                return s.edit_sets(p, id, req, expected)
            if op == "entry":
                return s.patch_entry(p, id, params["entry"], req, expected)
            if op == "group":
                return s.change_group(p, id, params["entry"], req.id, expected)
            if op == "ungroup":
                return s.change_group(p, id, params["entry"], params["group"], expected, True)
            if op == "complete":
                return s.complete(p, id, expected)
            if op == "reopen":
                return s.reopen(p, id, expected)
        if kind == "diary":
            if op == "create":
                return s.create_diary(p, req)
            if op == "update":
                return s.edit_diary(p, id, req, expected)
            if op == "delete":
                repo.delete(p, kind, id, expected)
                return Result(204, None)
        if kind == "goals":
            return s.save_goals(p, req, expected)
        if op == "update":
            old = (
                s.definition(p, kind, id) if kind in ("exercise", "food") else repo.get(p, kind, id)
            )
            fields = req.model_dump(exclude_unset=True)
            if kind == "recipe":
                # Existing ingredients are retained unless explicitly replaced by a full write list.
                original = old.value.model_dump(exclude={"ingredients", "version", "archived"})
                original["ingredients"] = tuple(
                    IngredientRequest(
                        id=i.id, food_id=i.food_id, grams=i.grams, retain_snapshot=True
                    )
                    for i in old.value.ingredients
                )
                req = RecipeWrite.model_validate({**original, **fields})
            else:
                req = changed(old.value, **fields)
        if kind in ("exercise", "food"):
            return s.save_definition(p, kind, req, expected)
        if kind == "template":
            return s.save_template(p, req, expected)
        if kind == "recipe":
            return s.save_recipe(p, req, expected)
        if kind == "profile":
            profile = Profile(**req.model_dump(exclude={"id"}))
            record = repo.put(p, "profile", profile, expected)
            return Result(route.status, record.dto(), record.revision)
        raise Problem(404, "NOT_FOUND")
