def resource(model, **extra):
    return create_model(
        model.__name__ + "Resource",
        __base__=model,
        owner_sub=(str | None, ...),
        revision=(int, ...),
        schema_version=(Literal[1], 1),
        created_at=(Stamp, ...),
        updated_at=(Stamp, ...),
        **extra,
    )


def patch_model(model):
    fields: dict[str, Any] = {}
    for name, field in model.model_fields.items():
        if name == "id":
            continue
        annotation = (
            Annotated[field.annotation, *field.metadata] if field.metadata else field.annotation
        )
        fields[name] = (annotation | None, Field(default=None, alias=field.alias))
    return create_model(model.__name__ + "Patch", __base__=Model, **fields)


